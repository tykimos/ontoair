    "// ===== FORCE LAYOUT =====\n"
    "function forceLayout(iter) {\n"
    "  iter = iter || 300;\n"
    "  const allIds = Object.keys(nodeMap);\n"
    "  const allEdges = [];\n"
    "  onto.subClassOf.forEach(([c, p]) => allEdges.push([c, p]));\n"
    "  onto.domains.forEach(d => allEdges.push([d.prop, d.cls]));\n"
    "  onto.ranges.forEach(r => allEdges.push([r.prop, r.cls]));\n"
    "  onto.types.forEach(([i, c]) => allEdges.push([i, c]));\n"
    "\n"
    "  allIds.forEach(id => { nodeMap[id].vx = 0; nodeMap[id].vy = 0; nodeMap[id].vz = 0; });\n"
    "  const k = 15;\n"
    "  for (let t = 0; t < iter; t++) {\n"
    "    for (let i = 0; i < allIds.length; i++) {\n"
    "      for (let j = i + 1; j < allIds.length; j++) {\n"
    "        const a = nodeMap[allIds[i]], b = nodeMap[allIds[j]];\n"
    "        const dx = a.x - b.x, dy = a.y - b.y, dz = a.z - b.z;\n"
    "        const d = Math.sqrt(dx * dx + dy * dy + dz * dz) + 0.1;\n"
    "        const f = k * k / d * 0.008;\n"
    "        a.vx += dx / d * f; a.vy += dy / d * f; a.vz += dz / d * f;\n"
    "        b.vx -= dx / d * f; b.vy -= dy / d * f; b.vz -= dz / d * f;\n"
    "      }\n"
    "    }\n"
    "    allEdges.forEach(([s, tgt]) => {\n"
    "      const a = nodeMap[s], b = nodeMap[tgt]; if (!a || !b) return;\n"
    "      const dx = b.x - a.x, dy = b.y - a.y, dz = b.z - a.z;\n"
    "      const d = Math.sqrt(dx * dx + dy * dy + dz * dz) + 0.1;\n"
    "      const f = (d - k * 2) * 0.003;\n"
    "      a.vx += dx / d * f; a.vy += dy / d * f; a.vz += dz / d * f;\n"
    "      b.vx -= dx / d * f; b.vy -= dy / d * f; b.vz -= dz / d * f;\n"
    "    });\n"
    "    allIds.forEach(id => {\n"
    "      const n = nodeMap[id];\n"
    "      n.x += n.vx * 0.5; n.y += n.vy * 0.5; n.z += n.vz * 0.5;\n"
    "      n.vx *= 0.85; n.vy *= 0.85; n.vz *= 0.85;\n"
    "    });\n"
    "  }\n"
    "  applyPositions();\n"
    "}\n"
    "\n"
    "function applyPositions() {\n"
    "  Object.keys(nodeMap).forEach(id => {\n"
    "    const m = nodeMeshes.find(m => m.userData.id === id);\n"
    "    if (m) m.position.set(nodeMap[id].x, nodeMap[id].y, nodeMap[id].z);\n"
    "  });\n"
    "  edgeObjs.forEach(line => {\n"
    "    const s = nodeMeshes.find(m => m.userData.id === line.userData.srcId);\n"
    "    const t = nodeMeshes.find(m => m.userData.id === line.userData.tgtId);\n"
    "    if (s && t) {\n"
    "      const pos = line.geometry.attributes.position;\n"
    "      pos.setXYZ(0, s.position.x, s.position.y, s.position.z);\n"
    "      pos.setXYZ(1, t.position.x, t.position.y, t.position.z);\n"
    "      pos.needsUpdate = true;\n"
    "      if (line.userData.labelSprite) line.userData.labelSprite.position.copy(s.position.clone().add(t.position).multiplyScalar(0.5));\n"
    "    }\n"
    "  });\n"
    "}\n"
    "\n"
    "// ===== CONTROLS =====\n"
    "document.getElementById('btn-force').addEventListener('click', () => {\n"
    "  forceLayout(400);\n"
    "  document.getElementById('btn-hier').classList.remove('active');\n"
    "  document.getElementById('btn-force').classList.add('active');\n"
    "});\n"
    "document.getElementById('btn-hier').addEventListener('click', () => {\n"
    "  hierLayout(); applyPositions();\n"
    "  document.getElementById('btn-hier').classList.add('active');\n"
    "  document.getElementById('btn-force').classList.remove('active');\n"
    "});\n"
    "document.getElementById('btn-reset').addEventListener('click', () => {\n"
    "  camera.position.set(0, 20, 55); ctrl.target.set(0, 0, 0);\n"
    "  document.getElementById('btn-hier').click();\n"
    "});\n"
    "\n"
    "window.addEventListener('resize', () => {\n"
    "  camera.aspect = innerWidth / innerHeight;\n"
    "  camera.updateProjectionMatrix();\n"
    "  renderer.setSize(innerWidth, innerHeight);\n"
    "});\n"
    "\n"
    "// ===== HUD =====\n"
    "document.getElementById('hud-filename').textContent = FILE_NAME;\n"
    "document.getElementById('hud-info').innerHTML =\n"
    "  onto.classes.length + ' owl:Class<br>' +\n"
    "  onto.objProps.length + ' ObjectProperty<br>' +\n"
    "  onto.dtProps.length + ' DatatypeProperty<br>' +\n"
    "  onto.annProps.length + ' AnnotationProperty<br>' +\n"
    "  onto.individuals.length + ' Individual<br>' +\n"
    "  onto.subClassOf.length + ' subClassOf<br>' +\n"
    "  edgeObjs.length + ' edges';\n"
    "\n"
    "// Auto-adjust camera based on node count\n"
    "const totalN = nodeMeshes.length;\n"
    "if (totalN > 50) camera.position.set(0, 30, 80);\n"
    "if (totalN > 100) camera.position.set(0, 40, 120);\n"
    "</script>\n"
    "</body>\n"
    "</html>\n";
}

OSStatus GeneratePreviewForURL(void *thisInterface, QLPreviewRequestRef preview,
                                CFURLRef url, CFStringRef contentTypeUTI,
                                CFDictionaryRef options) {
    (void)thisInterface;
    (void)contentTypeUTI;
    (void)options;

    @autoreleasepool {
        if (QLPreviewRequestIsCancelled(preview)) return noErr;

        // Read ontology file
        NSError *error = nil;
        NSString *content = [NSString stringWithContentsOfURL:(__bridge NSURL *)url
                                                     encoding:NSUTF8StringEncoding
                                                        error:&error];
        if (!content) {
            content = [NSString stringWithContentsOfURL:(__bridge NSURL *)url
                                               encoding:NSISOLatin1StringEncoding
                                                  error:&error];
        }
        if (!content) return noErr;

        if (QLPreviewRequestIsCancelled(preview)) return noErr;

        // Detect format and get filename
        NSString *format = detectFormat(url);
        NSString *fileName = [(__bridge NSURL *)url lastPathComponent];

        // Escape content for JavaScript embedding
        NSString *escaped = escapeForJS(content);

        // Build HTML
        NSString *template = getViewerHTML();

        // Inject data placeholders
        NSString *html = [template stringByReplacingOccurrencesOfString:@"ONTOAIR_RAW_CONTENT"
                                                            withString:[NSString stringWithFormat:@"`%@`", escaped]];
        html = [html stringByReplacingOccurrencesOfString:@"ONTOAIR_FILE_FORMAT"
                                              withString:[NSString stringWithFormat:@"'%@'", format]];
        html = [html stringByReplacingOccurrencesOfString:@"ONTOAIR_FILE_NAME"
                                              withString:[NSString stringWithFormat:@"'%@'", fileName]];

        // Return HTML to QuickLook
        NSDictionary *props = @{
            (__bridge NSString *)kQLPreviewPropertyTextEncodingNameKey: @"UTF-8",
            (__bridge NSString *)kQLPreviewPropertyMIMETypeKey: @"text/html"
        };

        QLPreviewRequestSetDataRepresentation(preview,
            (__bridge CFDataRef)[html dataUsingEncoding:NSUTF8StringEncoding],
            kUTTypeHTML,
            (__bridge CFDictionaryRef)props);
    }

    return noErr;
}

