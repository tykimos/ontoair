    "    hovered = hits[0].object;\n"
    "    hovered.material.color.setHex(0xf0f0f0);\n"
    "    // Highlight connected edges\n"
    "    edgeObjs.forEach(e => {\n"
    "      if (e.userData.srcId === d.id || e.userData.tgtId === d.id) e.material.color.setHex(0x333333);\n"
    "      else e.material.color.setHex(e.material._origColor || 0xbbbbbb);\n"
    "    });\n"
    "  } else {\n"
    "    if (hovered) hovered.material.color.setHex(0xffffff);\n"
    "    hovered = null;\n"
    "    tooltip.style.display = 'none';\n"
    "    edgeObjs.forEach(e => e.material.color.setHex(e.material._origColor || 0xbbbbbb));\n"
    "  }\n"
    "});\n"
    "\n"
    "// Store original edge colors\n"
    "edgeObjs.forEach(e => e.material._origColor = e.material.color.getHex());\n"
