    "    // Process remaining parts (same subject)\n"
    "    for (let i = 1; i < parts.length; i++) {\n"
    "      const tokens = parts[i].match(/\\S+/g);\n"
    "      if (tokens) processPredicateObject(tokens);\n"
    "    }\n"
    "  });\n"
    "\n"
    "  return result;\n"
    "}\n"
