    "          const typeName = localName(typeURI);\n"
    "          if (typeName === 'Class' || typeName === 'Class') {\n"
    "            if (!seen.has('c:'+s)) { seen.add('c:'+s); result.classes.push({ id: s, uri: expandURI(subject) }); }\n"
    "          } else if (typeName === 'ObjectProperty') {\n"
    "            if (!seen.has('op:'+s)) { seen.add('op:'+s); result.objProps.push({ id: s, uri: expandURI(subject) }); }\n"
    "          } else if (typeName === 'DatatypeProperty') {\n"
    "            if (!seen.has('dp:'+s)) { seen.add('dp:'+s); result.dtProps.push({ id: s, uri: expandURI(subject) }); }\n"
    "          } else if (typeName === 'AnnotationProperty') {\n"
    "            if (!seen.has('ap:'+s)) { seen.add('ap:'+s); result.annProps.push({ id: s, uri: expandURI(subject) }); }\n"
    "          } else if (typeName === 'Ontology' || typeName === 'Restriction') {\n"
    "            // skip\n"
    "          } else if (typeName === 'NamedIndividual') {\n"
    "            // Will be typed by another triple\n"
    "          } else {\n"
    "            if (!seen.has('i:'+s)) { seen.add('i:'+s); result.individuals.push({ id: s, uri: expandURI(subject), cls: typeName }); }\n"
    "            result.types.push([s, typeName]);\n"
    "          }\n"
    "        } else if (pLocal === 'subClassOf') {\n"
    "          result.subClassOf.push([s, o]);\n"
    "        } else if (pLocal === 'domain') {\n"
    "          result.domains.push({ prop: s, cls: o });\n"
