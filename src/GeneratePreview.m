    "    return curie;\n"
    "  }\n"
    "\n"
    "  function resolveName(curie) {\n"
    "    return localName(expandURI(curie));\n"
    "  }\n"
    "\n"
    "  // Remove prefix declarations from content\n"
    "  let body = content.replace(/@prefix\\s+\\w*:?\\s*<[^>]+>\\s*\\./g, '').replace(/PREFIX\\s+\\w*:?\\s*<[^>]+>/gi, '').trim();\n"
    "  // Also remove @base\n"
    "  body = body.replace(/@base\\s*<[^>]+>\\s*\\./g, '').trim();\n"
    "\n"
    "  // Split into statements (by '.')\n"
    "  // Handle nested brackets [...] and quoted strings\n"
    "  const statements = [];\n"
    "  let depth = 0, qchar = null, stmt = '';\n"
    "  for (let i = 0; i < body.length; i++) {\n"
    "    const c = body[i];\n"
    "    if (qchar) { stmt += c; if (c === qchar && body[i-1] !== '\\\\') qchar = null; continue; }\n"
    "    if (c === '\"' || c === \"'\") { qchar = c; stmt += c; continue; }\n"
    "    if (c === '[' || c === '(') { depth++; stmt += c; continue; }\n"
