    "renderer.setClearColor(0xffffff);\n"
    "\n"
    "const scene = new THREE.Scene();\n"
    "const camera = new THREE.PerspectiveCamera(50, innerWidth / innerHeight, 0.1, 800);\n"
    "camera.position.set(0, 20, 55);\n"
    "\n"
    "const ctrl = new OrbitControls(camera, canvas);\n"
    "ctrl.enableDamping = true;\n"
    "ctrl.dampingFactor = 0.05;\n"
    "\n"
    "scene.add(new THREE.AmbientLight(0xffffff, 1));\n"
    "const dirLight = new THREE.DirectionalLight(0xffffff, 0.3);\n"
    "dirLight.position.set(10, 20, 10);\n"
    "scene.add(dirLight);\n"
    "\n"
    "// ===== SHAPE GEOMETRIES =====\n"
    "function circGeo(r) { return new THREE.CircleGeometry(r, 32); }\n"
    "function triGeo(r) { const s = new THREE.Shape(); s.moveTo(0, r); s.lineTo(-r * .87, -r * .5); s.lineTo(r * .87, -r * .5); s.closePath(); return new THREE.ShapeGeometry(s); }\n"
    "function sqGeo(r) { const s = new THREE.Shape(), h = r * .8; s.moveTo(-h, -h); s.lineTo(h, -h); s.lineTo(h, h); s.lineTo(-h, h); s.closePath(); return new THREE.ShapeGeometry(s); }\n"
    "function diaGeo(r) { const s = new THREE.Shape(); s.moveTo(0, r); s.lineTo(r * .7, 0); s.lineTo(0, -r); s.lineTo(-r * .7, 0); s.closePath(); return new THREE.ShapeGeometry(s); }\n"
    "function starGeo(r) { const s = new THREE.Shape(); for (let i = 0; i < 5; i++) { const oa = i * 2 * Math.PI / 5 - Math.PI / 2, ia = oa + Math.PI / 5; if (!i) s.moveTo(Math.cos(oa) * r, Math.sin(oa) * r); else s.lineTo(Math.cos(oa) * r, Math.sin(oa) * r); s.lineTo(Math.cos(ia) * r * .45, Math.sin(ia) * r * .45); } s.closePath(); return new THREE.ShapeGeometry(s); }\n"
    "\n"
    "const GEO = {\n"
    "  Class: circGeo(1.2),\n"
    "  ObjectProperty: triGeo(1.1),\n"
    "  DatatypeProperty: sqGeo(1.1),\n"
    "  AnnotationProperty: starGeo(1.1),\n"
    "  Individual: diaGeo(1.1)\n"
    "};\n"
    "\n"
    "// ===== LAYOUT =====\n"
    "const nodeMap = {};\n"
    "const nodeMeshes = [];\n"
    "const edgeObjs = [];\n"
    "\n"
    "function hierLayout() {\n"
    "  const topClasses = onto.classes.filter(c => !onto.subClassOf.some(s => s[0] === c.id));\n"
    "  const subClasses = onto.classes.filter(c => onto.subClassOf.some(s => s[0] === c.id));\n"
    "\n"
    "  // Scale radius based on total node count\n"
    "  const totalNodes = onto.classes.length + onto.objProps.length + onto.dtProps.length + onto.annProps.length + onto.individuals.length;\n"
    "  const baseR = Math.max(12, Math.sqrt(totalNodes) * 4);\n"
    "\n"
    "  topClasses.forEach((c, i) => {\n"
    "    const angle = i / Math.max(topClasses.length, 1) * Math.PI * 2;\n"
    "    nodeMap[c.id] = { x: Math.cos(angle) * baseR, y: 5, z: Math.sin(angle) * baseR };\n"
    "  });\n"
    "\n"
    "  subClasses.forEach((c, i) => {\n"
    "    const parentId = onto.subClassOf.find(s => s[0] === c.id)?.[1];\n"
    "    const p = nodeMap[parentId];\n"
    "    if (p) {\n"
    "      const angle = i / Math.max(subClasses.length, 1) * Math.PI * 2;\n"
    "      nodeMap[c.id] = { x: p.x + Math.cos(angle) * 5, y: p.y - 5, z: p.z + Math.sin(angle) * 5 };\n"
    "    } else {\n"
    "      const angle = i / Math.max(subClasses.length, 1) * Math.PI * 2;\n"
    "      nodeMap[c.id] = { x: Math.cos(angle) * baseR * 0.6, y: 0, z: Math.sin(angle) * baseR * 0.6 };\n"
    "    }\n"
    "  });\n"
    "\n"
    "  // Properties positioned between domain/range\n"
    "  const allProps = [...onto.objProps.map(p => ({ ...p, t: 'ObjectProperty' })), ...onto.dtProps.map(p => ({ ...p, t: 'DatatypeProperty' })), ...onto.annProps.map(p => ({ ...p, t: 'AnnotationProperty' }))];\n"
    "  allProps.forEach((prop, i) => {\n"
    "    const domEntry = onto.domains.find(d => d.prop === prop.id);\n"
    "    const ranEntry = onto.ranges.find(r => r.prop === prop.id);\n"
    "    const d = domEntry ? nodeMap[domEntry.cls] : null;\n"
    "    const r = ranEntry ? nodeMap[ranEntry.cls] : null;\n"
    "    if (d && r) {\n"
    "      nodeMap[prop.id] = { x: (d.x + r.x) / 2 + (Math.random() - .5) * 3, y: (d.y + r.y) / 2 - 3, z: (d.z + r.z) / 2 + (Math.random() - .5) * 3 };\n"
    "    } else if (d) {\n"
    "      nodeMap[prop.id] = { x: d.x + (Math.random() - .5) * 6, y: d.y - 4, z: d.z + (Math.random() - .5) * 6 };\n"
    "    } else {\n"
    "      const angle = i / Math.max(allProps.length, 1) * Math.PI * 2;\n"
    "      nodeMap[prop.id] = { x: Math.cos(angle) * (baseR + 8), y: -8, z: Math.sin(angle) * (baseR + 8) };\n"
    "    }\n"
    "  });\n"
    "\n"
    "  // Individuals near their class\n"
    "  onto.individuals.forEach((inst, i) => {\n"
    "    const p = nodeMap[inst.cls];\n"
    "    if (p) {\n"
    "      const angle = i / Math.max(onto.individuals.length, 1) * Math.PI * 2;\n"
    "      nodeMap[inst.id] = { x: p.x + Math.cos(angle) * 5, y: p.y - 7, z: p.z + Math.sin(angle) * 5 };\n"
    "    } else {\n"
    "      const angle = i / Math.max(onto.individuals.length, 1) * Math.PI * 2;\n"
    "      nodeMap[inst.id] = { x: Math.cos(angle) * (baseR + 14), y: -12, z: Math.sin(angle) * (baseR + 14) };\n"
    "    }\n"
    "  });\n"
    "}\n"
    "\n"
    "hierLayout();\n"
    "\n"
    "// ===== SPRITE TEXT =====\n"
    "function makeLabel(text, size) {\n"
    "  size = size || 0.5;\n"
    "  const c = document.createElement('canvas'); c.width = 512; c.height = 64;\n"
    "  const x = c.getContext('2d');\n"
    "  x.font = 'bold 26px system-ui, -apple-system, sans-serif';\n"
    "  x.fillStyle = '#333'; x.textAlign = 'center'; x.textBaseline = 'middle';\n"
    "  // Truncate long labels\n"
    "  let label = text;\n"
    "  if (label.length > 24) label = label.substring(0, 22) + '...';\n"
    "  x.fillText(label, 256, 32);\n"
    "  const t = new THREE.CanvasTexture(c);\n"
    "  const m = new THREE.SpriteMaterial({ map: t, transparent: true, depthWrite: false });\n"
    "  const s = new THREE.Sprite(m);\n"
    "  s.scale.set(size * 8, size, 1);\n"
    "  return s;\n"
    "}\n"
    "\n"
    "// ===== CREATE NODES =====\n"
    "function makeNode(id, type, x, y, z, label, uri) {\n"
    "  const geo = GEO[type] || GEO.Class;\n"
    "  const mesh = new THREE.Mesh(geo, new THREE.MeshBasicMaterial({ color: 0xffffff, side: THREE.DoubleSide }));\n"
    "  mesh.position.set(x, y, z);\n"
    "  mesh.userData = { id, type, label: label || id, uri: uri || '' };\n"
    "  const eg = new THREE.EdgesGeometry(geo);\n"
    "  mesh.add(new THREE.LineSegments(eg, new THREE.LineBasicMaterial({ color: 0x333333 })));\n"
    "  const lbl = makeLabel(label || id, 0.4);\n"
    "  lbl.position.set(0, -1.6, 0);\n"
    "  mesh.add(lbl);\n"
    "  scene.add(mesh);\n"
    "  nodeMeshes.push(mesh);\n"
    "  return mesh;\n"
    "}\n"
    "\n"
    "// Build nodes\n"
    "onto.classes.forEach(c => { const p = nodeMap[c.id]; if (p) makeNode(c.id, 'Class', p.x, p.y, p.z, c.id, c.uri); });\n"
    "onto.objProps.forEach(c => { const p = nodeMap[c.id]; if (p) makeNode(c.id, 'ObjectProperty', p.x, p.y, p.z, c.id, c.uri); });\n"
    "onto.dtProps.forEach(c => { const p = nodeMap[c.id]; if (p) makeNode(c.id, 'DatatypeProperty', p.x, p.y, p.z, c.id, c.uri); });\n"
    "onto.annProps.forEach(c => { const p = nodeMap[c.id]; if (p) makeNode(c.id, 'AnnotationProperty', p.x, p.y, p.z, c.id, c.uri); });\n"
    "onto.individuals.forEach(c => { const p = nodeMap[c.id]; if (p) makeNode(c.id, 'Individual', p.x, p.y, p.z, c.id, c.uri); });\n"
    "\n"
    "// ===== CREATE EDGES =====\n"
    "function addEdge(srcId, tgtId, label, dashed, color) {\n"
    "  const srcMesh = nodeMeshes.find(m => m.userData.id === srcId);\n"
    "  const tgtMesh = nodeMeshes.find(m => m.userData.id === tgtId);\n"
    "  if (!srcMesh || !tgtMesh) return;\n"
    "  const geo = new THREE.BufferGeometry().setFromPoints([srcMesh.position.clone(), tgtMesh.position.clone()]);\n"
    "  const mat = new THREE.LineBasicMaterial({ color: color || 0xbbbbbb });\n"
    "  if (dashed) { /* solid fallback for compatibility */ }\n"
    "  const line = new THREE.Line(geo, mat);\n"
    "  line.userData = { srcId, tgtId, label };\n"
    "  scene.add(line);\n"
    "  edgeObjs.push(line);\n"
    "  if (label) {\n"
    "    const mid = srcMesh.position.clone().add(tgtMesh.position).multiplyScalar(0.5);\n"
    "    const lbl = makeLabel(label, 0.25);\n"
    "    lbl.position.copy(mid);\n"
    "    scene.add(lbl);\n"
    "    line.userData.labelSprite = lbl;\n"
    "  }\n"
    "}\n"
    "\n"
    "// subClassOf\n"
    "onto.subClassOf.forEach(([child, parent]) => addEdge(child, parent, 'subClassOf', false, 0x333333));\n"
    "// domain\n"
    "onto.domains.forEach(d => addEdge(d.prop, d.cls, 'domain', false, 0x888888));\n"
    "// range\n"
    "onto.ranges.forEach(r => addEdge(r.prop, r.cls, 'range', false, 0x888888));\n"
    "// rdf:type\n"
    "onto.types.forEach(([inst, cls]) => addEdge(inst, cls, 'a', true, 0xaaaaaa));\n"
    "\n"
    "// ===== INTERACTION =====\n"
    "const raycaster = new THREE.Raycaster();\n"
    "const mouse = new THREE.Vector2();\n"
    "const tooltip = document.getElementById('tooltip');\n"
    "let hovered = null;\n"
    "\n"
    "canvas.addEventListener('mousemove', e => {\n"
    "  mouse.x = (e.clientX / innerWidth) * 2 - 1;\n"
    "  mouse.y = -(e.clientY / innerHeight) * 2 + 1;\n"
    "  raycaster.setFromCamera(mouse, camera);\n"
    "  const hits = raycaster.intersectObjects(nodeMeshes);\n"
    "  if (hits.length && hits[0].object.userData.id) {\n"
