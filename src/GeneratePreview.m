NSString *escapeForJS(NSString *str) {
    NSMutableString *escaped = [str mutableCopy];
    [escaped replaceOccurrencesOfString:@"\\" withString:@"\\\\" options:0 range:NSMakeRange(0, escaped.length)];
    [escaped replaceOccurrencesOfString:@"`" withString:@"\\`" options:0 range:NSMakeRange(0, escaped.length)];
    [escaped replaceOccurrencesOfString:@"$" withString:@"\\$" options:0 range:NSMakeRange(0, escaped.length)];
    return [escaped copy];
}

NSString *detectFormat(CFURLRef url) {
    NSString *path = [(__bridge NSURL *)url path];
    NSString *ext = [[path pathExtension] lowercaseString];
    if ([ext isEqualToString:@"owl"]) return @"owl";
    if ([ext isEqualToString:@"rdf"]) return @"rdf";
    if ([ext isEqualToString:@"ttl"]) return @"ttl";
    return @"ttl";
}

